const fs = require("node:fs");
const path = require("node:path");

function exportAbi(contractName, artifactName = contractName) {
  const artifactPath = path.join(
    process.cwd(),
    "artifacts",
    "contracts",
    `${contractName}.sol`,
    `${artifactName}.json`,
  );

  const outputDir = path.join(process.cwd(), "src", "abis");
  const outputPath = path.join(outputDir, `${artifactName}.ts`);
  const constName = `${artifactName.toUpperCase()}_ABI`;

  if (!fs.existsSync(artifactPath)) {
    console.error(`Artifact not found at ${artifactPath}. Skipping.`);
    return;
  }

  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  const abi = artifact.abi;

  fs.mkdirSync(outputDir, { recursive: true });
  const header = "/** Auto-generated by pnpm compile; do not edit manually. */\n";
  const body = header + `export const ${constName} = ` + JSON.stringify(abi, null, 2) + " as const;\n";
  fs.writeFileSync(outputPath, body);

  console.log(`${artifactName} ABI written to ${outputPath}`);
}

function main() {
  console.log("Exporting ABIs...\n");
  exportAbi("MockUSDC");
  exportAbi("Stake");
  console.log("\n✅ All ABIs exported successfully!");
}

main();
